function channelTypeRoot(channel: ChannelDef, event: string, suffix: string): string {
  const facade = channel.sdkName ?? channel.className.replace(/Channel$/, "");
  return `ChannelPayloads.${pascalCase(`${facade}Channel`)}.${pascalCase(event)}.${suffix}`;
}

function joinPayloadName(channel: ChannelDef, joinDef: ChannelJoinDef, index: number): string {
  return channelTypeRoot(channel, joinDef.sdkTypeName ?? joinDef.name ?? `join_${index + 1}`, "Params");
}

function messageInputName(channel: ChannelDef, message: ChannelMessageDef): string {
  return channelTypeRoot(channel, message.sdkTypeName ?? message.event, "Input");
}

function messageResponseName(channel: ChannelDef, message: ChannelMessageDef): string {
  return channelTypeRoot(channel, message.sdkTypeName ?? message.event, "Response");
}

function pushPayloadName(channel: ChannelDef, push: ChannelPushDef): string {
  return channelTypeRoot(channel, push.sdkTypeName ?? push.event, "Payload");
}

function joinResponseName(channel: ChannelDef, joinDef: ChannelJoinDef, index: number): string {
  return channelTypeRoot(channel, joinDef.sdkTypeName ?? joinDef.name ?? `join_${index + 1}`, "Response");
}

function emitChannel(channel: ChannelDef): string {
  const cb = new CodeBuilder("  ");
  beginFile(cb);
  channel.joins.forEach((joinDef, index) => {
    const topicParams = topicParamNames(joinDef.topicPattern);
    const payload = joinDef.params.filter(
      (param) => !topicParams.some((placeholder) => matchesTopicParam(param, placeholder))
    );
    if (payload.length > 0) {
      emitInlineStructs(
        cb,
        joinPayloadName(channel, joinDef, index),
        queryLikeFields(payload),
        joinDef.description,
        paramWireNames(payload)
      );
    }
    if (joinDef.returnType.kind === "object" && joinDef.returnType.fields.length > 0) {
      emitInlineStructs(cb, joinResponseName(channel, joinDef, index), joinDef.returnType.fields, joinDef.description);
    } else {
      joinDef.returnType = emitNestedTypeStructs(
        cb,
        joinDef.returnType,
        joinResponseName(channel, joinDef, index),
        joinDef.description
      );
    }
  });
  for (const message of channel.messages) {
    if (message.params.length > 0) {
      emitInlineStructs(
        cb,
        messageInputName(channel, message),
        queryLikeFields(message.params),
        message.description,
        paramWireNames(message.params)
      );
    }
    if (message.returnType.kind === "object" && message.returnType.fields.length > 0) {
      emitInlineStructs(cb, messageResponseName(channel, message), message.returnType.fields, message.description);
    } else {
      message.returnType = emitNestedTypeStructs(
        cb,
        message.returnType,
        messageResponseName(channel, message),
        message.description
      );
    }
  }
  for (const push of channel.pushes) {
    if (push.payloadType.kind === "object" && push.payloadType.fields.length > 0) {
      emitInlineStructs(cb, pushPayloadName(channel, push), push.payloadType.fields, push.description);
    } else {
      push.payloadType = emitNestedTypeStructs(
        cb,
        push.payloadType,
        pushPayloadName(channel, push),
        push.description
      );
    }
  }

  const moduleName = `ArchAstro.Channels.${exModuleSegment(channel.sdkName ?? channel.className.replace(/Channel$/, ""))}`;
  cb.line(`defmodule ${moduleName} do`);
  cb.indent();
  cb.line(`@moduledoc ${heredoc(channel.description ?? `${channel.name} Phoenix channel.`)}`);
  const memberNames = uniqueExFunctionNames(
    [
      ...channel.joins.map((joinDef, index) => joinDef.name ?? (channel.joins.length > 1 ? `join_${index + 1}` : "join")),
      ...channel.messages.map((message) => message.event),
      ...channel.pushes.map((push) => `subscribe_${push.event}`),
    ],
    ["leave"]
  );
  channel.joins.forEach((joinDef, index) =>
    emitChannelJoin(cb, channel, joinDef, index, moduleName, memberNames[index]!)
  );
  channel.messages.forEach((message, index) =>
    emitChannelMessage(cb, channel, message, memberNames[channel.joins.length + index]!)
  );
  channel.pushes.forEach((push, index) =>
    emitChannelPush(
      cb,
      channel,
      push,
      memberNames[channel.joins.length + channel.messages.length + index]!
    )
  );
  cb.line();
  cb.line("@spec leave(ArchAstro.Channel.t()) :: :ok | {:error, ArchAstro.Error.reason()}");
  cb.line("def leave(channel), do: ArchAstro.Channel.leave(channel)");
  cb.dedent();
  cb.line("end");
  return cb.toString();
}

function queryLikeFields(params: ParamDef[]): FieldDef[] {
  return params.map((param) => ({ ...param }));
}

function topicParamNames(pattern: string): string[] {
  return [...new Set([...pattern.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]!))];
}

function matchesTopicParam(param: ParamDef, placeholder: string): boolean {
  return param.name === placeholder || param.wireName === placeholder;
}

function emitChannelJoin(
  cb: CodeBuilder,
  channel: ChannelDef,
  joinDef: ChannelJoinDef,
  index: number,
  moduleName: string,
  name: string
): void {
  const topicParams = topicParamNames(joinDef.topicPattern);
  const payloadParams = joinDef.params.filter(
    (param) => !topicParams.some((placeholder) => matchesTopicParam(param, placeholder))
  );
  const topicLocals = uniqueExFunctionNames(topicParams, ["socket", "params", "topic"]);
  const args = ["socket", ...topicLocals];
  const specs = [
    "GenServer.server()",
    ...topicParams.map((name) => {
      const param = joinDef.params.find((candidate) => matchesTopicParam(candidate, name));
      return param ? typeSpec(param.type) : "String.t()";
    }),
  ];
  let payload = "%{}";
  if (payloadParams.length > 0) {
    const type = typeModule(joinPayloadName(channel, joinDef, index));
    payload = "params";
    args.push(payloadParams.some((param) => param.required) ? "params" : `params \\\\ %${type}{}`);
    specs.push(`${type}.t()`);
  }
  cb.line();
  cb.line(`@spec ${name}(${specs.join(", ")}) :: {:ok, ArchAstro.Channel.t()} | {:error, ArchAstro.Error.reason()}`);
  cb.line(`def ${name}(${args.join(", ")}) do`);
  cb.indent();
  const topic = interpolatedString(
    joinDef.topicPattern,
    topicParams.map((param, topicIndex) => ({
      patterns: [`{${param}}`],
      expression: topicLocals[topicIndex]!,
    }))
  );
  cb.line(`topic = ${topic}`);
  cb.line(`ArchAstro.Channel.join(socket, topic, ${payload}, ${moduleName}, ${channelTypeDescriptor(joinDef.returnType, joinResponseName(channel, joinDef, index))})`);
  cb.dedent();
  cb.line("end");
}

function emitChannelMessage(
  cb: CodeBuilder,
  channel: ChannelDef,
  message: ChannelMessageDef,
  name: string
): void {
  const args = ["channel"];
  const specs = ["ArchAstro.Channel.t()"];
  let payload = "%{}";
  if (message.params.length > 0) {
    const type = typeModule(messageInputName(channel, message));
    args.push(message.params.some((param) => param.required) ? "payload" : `payload \\\\ %${type}{}`);
    specs.push(`${type}.t()`);
    payload = "payload";
  }
  args.push("timeout \\\\ 5_000");
  specs.push("timeout()");
  const responseType = channelTypeSpec(message.returnType, messageResponseName(channel, message));
  cb.line();
  cb.line(`@spec ${name}(${specs.join(", ")}) :: {:ok, ${responseType}} | {:error, ArchAstro.Error.reason()}`);
  cb.line(`def ${name}(${args.join(", ")}) do`);
  cb.indent();
  cb.line(`ArchAstro.Channel.push(channel, ${exString(message.event)}, ${payload}, ${channelTypeDescriptor(message.returnType, messageResponseName(channel, message))}, timeout)`);
  cb.dedent();
  cb.line("end");
}

function emitChannelPush(
  cb: CodeBuilder,
  channel: ChannelDef,
  push: ChannelPushDef,
  name: string
): void {
  cb.line();
  cb.line(`@spec ${name}(ArchAstro.Channel.t(), pid()) :: :ok`);
  cb.line(`def ${name}(channel, subscriber \\\\ self()) do`);
  cb.indent();
  cb.line(`ArchAstro.Channel.subscribe(channel, ${exString(push.event)}, subscriber, ${channelTypeDescriptor(push.payloadType, pushPayloadName(channel, push))})`);
  cb.dedent();
  cb.line("end");
}

function channelTypeSpec(type: TypeRef, inlineName: string): string {
  if (type.kind === "object" && type.fields.length > 0) return `${typeModule(inlineName)}.t()`;
  if (type.kind === "object") return "ArchAstro.JSON.object() | :ok";
  return typeSpec(type);
}

function channelTypeDescriptor(type: TypeRef, inlineName: string): string {
  return type.kind === "object" && type.fields.length > 0 ? `{:ref, ${typeModule(inlineName)}}` : descriptor(type);
}

function typeSpec(type: TypeRef): string {
  switch (type.kind) {
    case "primitive":
      return type.type === "string" ? "String.t()" : type.type === "integer" ? "integer()" :
        type.type === "float" ? "number()" : type.type === "boolean" ? "boolean()" : "DateTime.t()";
    case "array": return `[${typeSpec(type.items)}]`;
    case "object": return type.fields.length === 0 ? "ArchAstro.JSON.object()" : objectMapSpec(type.fields);
    case "ref": return `${typeModule(type.schema)}.t()`;
    // Elixir typespecs do not support singleton binary literals. Keep the
    // wire representation honest instead of claiming these decode as atoms.
    case "enum": return "String.t()";
    case "union": return type.variants.map(typeSpec).join(" | ") || "ArchAstro.JSON.t()";
    case "nullable": return `${typeSpec(type.inner)} | nil`;
    case "optional": return typeSpec(type.inner);
    case "map": return `%{optional(${typeSpec(type.keyType)}) => ${typeSpec(type.valueType)}}`;
    case "void": return ":ok";
    case "unknown": return "ArchAstro.JSON.t()";
  }
}

function objectMapSpec(fields: ReadonlyArray<FieldDef>): string {
  const values = [...new Set(fields.map((field) => typeSpec(field.type)))];
  return `%{optional(String.t()) => ${values.join(" | ") || "ArchAstro.JSON.t()"}}`;
}

function descriptor(type: TypeRef): string {
  switch (type.kind) {
    case "primitive": return `:${type.type}`;
    case "array": return `{:list, ${descriptor(type.items)}}`;
    case "object": return `{:object, ${fieldDescriptors(type.fields)}}`;
    case "ref": return `{:ref, ${typeModule(type.schema)}}`;
    case "enum": return `{:enum, ${inspectList(type.values)}}`;
    case "union": {
      const variants = `[${type.variants.map(descriptor).join(", ")}]`;
      if (type.discriminator) {
      const inferredMapping = Object.fromEntries(
        type.variants
          .filter((variant): variant is Extract<TypeRef, { kind: "ref" }> => variant.kind === "ref")
          .map((variant) => [variant.schema, variant.schema])
      );
      const mapping = Object.entries(type.discriminator.mapping ?? inferredMapping)
          .map(([tag, schema]) => `${exString(tag)} => ${typeModule(schema)}`).join(", ");
        return `{:union, ${variants}, {${exString(type.discriminator.propertyName)}, %{${mapping}}}}`;
      }
      return `{:union, ${variants}}`;
    }
    case "nullable": return `{:nullable, ${descriptor(type.inner)}}`;
    case "optional": return `{:optional, ${descriptor(type.inner)}}`;
    case "map": return `{:map, ${descriptor(type.valueType)}}`;
    case "void": return ":void";
    case "unknown": return ":unknown";
  }
}

function fieldDescriptors(fields: ReadonlyArray<FieldDef>): string {
  return `[${fields.map((field) => `{${exString(field.name)}, ${fieldDescriptor(field)}}`).join(", ")}]`;
}

function fieldDescriptor(field: FieldDef): string {
  const value = descriptor(field.type);
  return field.required || field.type.kind === "optional" ? value : `{:optional, ${value}}`;
}

function inspectList(values: string[]): string {
  return `[${values.map(exString).join(", ")}]`;
}

function heredoc(value: string): string {
  const clean = value
    .replace(/\\/g, "\\\\")
    .replace(/"""/g, '\\"\\"\\"')
    .replace(/#\{/g, "\\#{")
    .trim();
  return `"""\n${clean}\n"""`;
}

function interpolatedString(
  value: string,
  replacements: ReadonlyArray<{ patterns: string[]; expression: string }>
): string {
  let template = value;
  const tokens: string[] = [];
  replacements.forEach((replacement, index) => {
    let token = `__ARCHASTRO_INTERPOLATION_${index}__`;
    while (template.includes(token)) token = `_${token}`;
    for (const pattern of replacement.patterns) template = template.split(pattern).join(token);
    tokens.push(token);
  });
  let literal = exString(template);
  replacements.forEach((replacement, index) => {
    literal = literal.split(tokens[index]!).join(`#{${replacement.expression}}`);
  });
  return literal;
}

